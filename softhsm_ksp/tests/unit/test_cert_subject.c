#define CERT_LEN        (sizeof(g_cert))
#define SUBJECT_OFFSET  143
#define SUBJECT_LEN     61

int main(void)
{
    const BYTE *pSubj = NULL;
    DWORD       cbSubj = 0;
    BOOL        ok;

    /* ── Suite 1 : a real certificate ───────────────────────────────────── */
    TEST_SUITE("P11_ExtractCertSubject — a real certificate");

    ASSERT_EQ("The embedded certificate is 859 bytes", (DWORD)CERT_LEN, 859U);

    ok = P11_ExtractCertSubject(g_cert, (DWORD)CERT_LEN, &pSubj, &cbSubj);
    ASSERT("Subject located", ok);
    ASSERT_EQ("at the offset openssl asn1parse reports",
        (DWORD)(pSubj - g_cert), (DWORD)SUBJECT_OFFSET);
    ASSERT_EQ("with the length openssl asn1parse reports",
        cbSubj, (DWORD)SUBJECT_LEN);

    /* CKA_SUBJECT is the whole encoded Name, header included. */
    ASSERT_EQ("It starts with a SEQUENCE tag", pSubj[0], (BYTE)0x30);
    ASSERT_EQ("whose length byte matches the span",
        (DWORD)pSubj[1] + 2, cbSubj);

    /* The common name is inside it, which is the point of the attribute. */
    {
        const char *pszCn = "phase7.example";
        BOOL bFound = FALSE;
        DWORD i;
        for (i = 0; i + strlen(pszCn) <= cbSubj; i++) {
            if (memcmp(pSubj + i, pszCn, strlen(pszCn)) == 0) {
                bFound = TRUE;
                break;
            }
        }
        ASSERT("and the common name is inside it", bFound);
    }

    /* This certificate is self-signed, so issuer and subject encode
     * identically — a useful cross-check that the walk stopped at the
     * right element rather than one too early. */
    {
        const BYTE *pIssuer = g_cert + 50;    /* from asn1parse */
        ASSERT("Subject is not the issuer field itself", pSubj != pIssuer);
        ASSERT("though for a self-signed certificate they encode alike",
            memcmp(pSubj, pIssuer, cbSubj) == 0);
    }

    /* ── Suite 2 : refusing what it cannot parse ────────────────────────── */
    TEST_SUITE("Malformed input");

    ASSERT("NULL is refused",
        !P11_ExtractCertSubject(NULL, 10, &pSubj, &cbSubj));
    ASSERT("Zero length is refused",
        !P11_ExtractCertSubject(g_cert, 0, &pSubj, &cbSubj));
    ASSERT("A NULL out-pointer is refused",
        !P11_ExtractCertSubject(g_cert, (DWORD)CERT_LEN, NULL, &cbSubj));
    ASSERT("A NULL length pointer is refused",
        !P11_ExtractCertSubject(g_cert, (DWORD)CERT_LEN, &pSubj, NULL));

    {
        /* Not a SEQUENCE. */
        static const BYTE abJunk[] = { 0x02, 0x01, 0x05 };
        ASSERT("An INTEGER at the top level is refused",
            !P11_ExtractCertSubject(abJunk, (DWORD)sizeof(abJunk),
                                    &pSubj, &cbSubj));
    }

    {
        /* A length that claims more than the buffer holds — the shape of
         * the bug this project already shipped once. */
        static const BYTE abLying[] = { 0x30, 0x7F, 0x30, 0x01 };
        ASSERT("A length past the end of the buffer is refused",
            !P11_ExtractCertSubject(abLying, (DWORD)sizeof(abLying),
                                    &pSubj, &cbSubj));
    }

    {
        /* Indefinite-length form: legal BER, forbidden in DER. */
        static const BYTE abIndef[] = { 0x30, 0x80, 0x30, 0x00, 0x00, 0x00 };
        ASSERT("The indefinite length form is refused",
            !P11_ExtractCertSubject(abIndef, (DWORD)sizeof(abIndef),
                                    &pSubj, &cbSubj));
    }

    {
        /* More length bytes than a DWORD can hold. */
        static const BYTE abHuge[] = { 0x30, 0x85, 1, 2, 3, 4, 5 };
        ASSERT("An over-long length field is refused",
            !P11_ExtractCertSubject(abHuge, (DWORD)sizeof(abHuge),
                                    &pSubj, &cbSubj));
    }

    /* ── Suite 3 : every truncation of a valid certificate ──────────────── */
    TEST_SUITE("Truncation");

    {
        /* The parser must never read past what it was given. Under
         * AddressSanitizer this loop is the real test; without it, the
         * assertion below still catches a subject that claims to extend
         * beyond the buffer. */
        DWORD cb;
        BOOL  bAnyOverrun = FALSE;

        for (cb = 1; cb < CERT_LEN; cb++) {
            const BYTE *p = NULL;
            DWORD       n = 0;
            if (P11_ExtractCertSubject(g_cert, cb, &p, &n)) {
                if (p < g_cert || p + n > g_cert + cb)
                    bAnyOverrun = TRUE;
            }
        }
        ASSERT("No truncation yields a subject outside the buffer",
            !bAnyOverrun);

        /* A certificate cut before the subject cannot produce one. */
        {
            const BYTE *p = NULL;
            DWORD       n = 0;
            ASSERT("Cut before the subject → no subject",
                !P11_ExtractCertSubject(g_cert, SUBJECT_OFFSET, &p, &n));
        }
    }

    TEST_REPORT();
    TEST_EXIT();
}
