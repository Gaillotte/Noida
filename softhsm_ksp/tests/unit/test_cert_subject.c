/* test_cert_subject.c — P11_ExtractCertSubject
 *
 * PKCS#11 marks CKA_SUBJECT required for an X.509 certificate object.
 * SoftHSM2 does not enforce it, so the provider originally omitted it and
 * said so in a comment: a stricter token would refuse, and writing a
 * workaround with no such token to test against is how this project
 * accumulated code that only worked against its own assumptions.
 *
 * Kryoptic is that stricter token — CKR_TEMPLATE_INCONSISTENT — so the
 * subject is now parsed out of the certificate. This suite is the reason
 * that parser can be trusted.
 *
 * The certificate below is real, produced by `openssl req -x509` and
 * embedded byte for byte. Its subject is at offset 143 and is 61 bytes
 * including the SEQUENCE header, confirmed with `openssl asn1parse`. Every
 * expectation here comes from OpenSSL, not from this parser agreeing with
 * itself.
 *
 * The malformed cases matter as much as the good one. This project has
 * already shipped an out-of-bounds read in DER handling
 * (P11_DecodeDerEcdsaSignature, caught with AddressSanitizer), so every
 * truncation of a valid certificate is walked here — if any read runs past
 * the buffer, an ASan build fails on it.
 */
